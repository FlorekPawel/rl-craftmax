from pathlib import Path

REPO_URL = "https://github.com/FlorekPawel/rl-craftmax"
DATASET_ID = "Pawlo77/wut-murl-craftax-results"
SPACE_ID = "Pawlo77/wut-murl-craftax"

NOTICE = """Third-party notices

- Craftax (MIT, Matthews et al.): the environment all runs use.
- training/ppo.py and training/wrappers.py: portions from Craftax_Baselines, MIT, Copyright (c) 2024 Michael Matthews.
- training/batch_renorm.py: Apache-2.0, ported from purejaxql and Flax.
- Video music is generated by this project and released under CC0; the narration is synthetic. No audio files are in this dataset.
"""

_ROWS = {
    "mlruns.db": "scrubbed MLflow store (no user, host or local path)",
    "mlruns/": "per-run artifacts: config, metrics, episodes, evaluation tables (no checkpoints)",
    "metrics/": "per-run evaluation exports (parquet)",
    "results/": "report figures and tables",
    "analysis/": "hard scenarios, cases and obstacle tables per budget and method",
    "interpretation/": "distilled decision-tree rules, fidelity and complexity",
    "checkpoints/": "final parameters (`final.msgpack`) of every final run and seed",
    "media/": "GIFs and videos",
    "report/": "the report PDF",
}


def _mb(n: int) -> str:
    return f"{n / 1e6:,.1f} MB"


def dataset_card(sizes: dict[str, int], commit: str) -> str:
    """Card with the measured size of every top-level entry in `sizes`."""
    table = "\n".join(
        f"| `{k}` | {v} | {_mb(sizes[k])} |" for k, v in _ROWS.items() if k in sizes
    )
    return f"""---
license: mit
pretty_name: Craftax results (wut_murl_craftax)
task_categories:
- reinforcement-learning
tags: [craftax, jax, mlflow, reinforcement-learning]
---
# Craftax results

Training runs, evaluation exports, analysis, decision rules and final checkpoints of the
course project [wut_murl_craftax]({REPO_URL}) (commit `{commit}`): textbook RL methods and
published agents on Craftax-Symbolic-v1 (craftax 1.7.0) at 1M and 1B environment steps.
Demo: https://huggingface.co/spaces/{SPACE_ID}

| Path | Content | Size |
|---|---|---|
{table}

## Use

- MLflow: `mlflow ui --backend-store-uri sqlite:///mlruns.db` next to the `mlruns/` folder.
- Metrics: `pandas.read_parquet("metrics/<run id>/eval_0_greedy.parquet")`.
- Checkpoints: `flax.serialization.msgpack_restore(open("final.msgpack", "rb").read())`.

## Limitations

Single environment, 10 seeds at 1M and 3 at 1B; scores are not comparable to other
benchmarks without the same protocol. Evaluation protocol and metric definitions are in the
report and the repository notes.

## Licence

MIT for everything here ({REPO_URL}); third-party notices in `NOTICE`. Cite with the
repository's `CITATION.cff`.
"""


def model_card(meta: dict[str, str]) -> str:
    """Card of one final checkpoint; `meta` has method, budget and seed."""
    return f"""---
license: mit
tags: [craftax, reinforcement-learning, jax]
---
# {meta["method"]} ({meta["budget"]} steps, seed {meta["seed"]})

Final parameters of `{meta["method"]}` trained on Craftax-Symbolic-v1 (craftax 1.7.0) for
{meta["budget"].upper()} environment steps, seed {meta["seed"]}; `config.json` holds its
configuration, the run's scores are in the dataset's `metrics/` and `mlruns.db`.

```python
from flax import serialization
params = serialization.msgpack_restore(open("final.msgpack", "rb").read())
```

Intended use: research and teaching. Limitation: trained and evaluated on one environment.
Source: {REPO_URL}.
"""


def space_card() -> str:
    """Front matter and one line for the static Space."""
    return f"""---
title: Craftax results
emoji: 🎮
colorFrom: green
colorTo: blue
sdk: static
app_file: index.html
license: mit
short_description: Results of RL methods on Craftax
datasets:
- {DATASET_ID}
---
Results tables, plots and GIFs of [wut_murl_craftax]({REPO_URL}).
"""


def write_text(path: Path, text: str) -> None:
    """Write `text` to `path`, creating its folder."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
